"""Offline UI atlas generation; Pillow is not a game/build dependency.

Usage: python3 tools/generate_ui_font.py /path/to/DejaVuSansMono.ttf
The checked-in header is embedded in GDP, including Windows portable builds.
"""
import argparse
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("font", type=Path)
args = parser.parse_args()
factor = 3  # Keep the logo crisp as well as the smaller menu/HUD text.
font = ImageFont.truetype(str(args.font), 24 * factor)
first_codepoint, last_codepoint = 32, 255
columns = 16
cell_width, cell_height, baseline = 20, 32, 25
atlas_rows = (last_codepoint - first_codepoint + columns) // columns
image = Image.new("L", (cell_width * columns * factor, cell_height * atlas_rows * factor))
draw = ImageDraw.Draw(image)
for index, code in enumerate(range(first_codepoint, last_codepoint + 1)):
    # Accented capitals must not spill into the preceding cell; descenders need room too.
    bounds = font.getbbox(chr(code), anchor="ls")
    assert bounds[0] + 2 * factor >= 0 and bounds[2] + 2 * factor <= cell_width * factor
    assert bounds[1] + baseline * factor >= 0 and bounds[3] + baseline * factor <= cell_height * factor
    draw.text(((index % columns * cell_width + 2) * factor, (index // columns * cell_height + baseline) * factor), chr(code),
              font=font, fill=255, anchor="ls")
# Count/value RLE; no external files or decompressor needed at runtime.
runs = []
for value in image.tobytes():
    if runs and runs[-1][1] == value and runs[-1][0] < 255:
        runs[-1][0] += 1
    else:
        runs.append([1, value])
data = [value for pair in runs for value in pair]
rows = ["    " + ",".join(str(v) for v in data[i:i + 32]) + "," for i in range(0, len(data), 32)]
root = Path(__file__).resolve().parents[1]
header = """// Generated by tools/generate_ui_font.py; do not edit raster data.
// DejaVu Sans Mono, Copyright (c) 2003 Bitstream, Inc.; DejaVu changes public domain.
// Redistribution notice: assets/fonts/LICENSE-DejaVu.txt.
#pragma once
#include <array>
#include <cstdint>
namespace gdp::game::visual {
inline constexpr int uiFontAtlasWidth = %d;
inline constexpr int uiFontAtlasHeight = %d;
inline constexpr int uiFontFirstCodepoint = 32;
inline constexpr int uiFontLastCodepoint = 255;
inline constexpr int uiFontAtlasColumns = 16;
inline constexpr int uiFontAtlasRows = 14;
inline constexpr int uiFontCellHeight = 32;
inline constexpr int uiFontBaseline = 25;
inline constexpr std::array<std::uint8_t, %d> uiFontAtlasRle{
%s
};
} // namespace gdp::game::visual
""" % (image.width, image.height, len(data), "\n".join(rows))
(root / "src/game/visual/UiFontAtlas.hpp").write_text(header, encoding="utf-8")
print(f"Embedded atlas: {image.width}x{image.height}, {len(data)} RLE bytes")
